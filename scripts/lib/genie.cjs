// scripts/lib/genie.cjs
// Project Genie Simulator - Procedural World Generation
// Creates varied React Three Fiber components based on directives.

const generateEvolutionComponent = (directive, name) => {
  const timestamp = new Date().toISOString();

  // Basic procedural logic based on keywords
  const isFire = directive.toLowerCase().includes('fire') || directive.toLowerCase().includes('burn') || directive.toLowerCase().includes('ember');
  const isIce = directive.toLowerCase().includes('ice') || directive.toLowerCase().includes('freeze') || directive.toLowerCase().includes('crystal');
  const isVoid = directive.toLowerCase().includes('void') || directive.toLowerCase().includes('dark') || directive.toLowerCase().includes('shadow');
  const isGold = directive.toLowerCase().includes('gold') || directive.toLowerCase().includes('wealth') || directive.toLowerCase().includes('aura');
  const isNature = directive.toLowerCase().includes('nature') || directive.toLowerCase().includes('growth') || directive.toLowerCase().includes('tendril');

  // Select geometry based on type
  let geometryJsx = '<torusKnotGeometry args={[1, 0.3, 128, 32]} />';

  if (isIce) geometryJsx = '<octahedronGeometry args={[1.5, 0]} />';
  else if (isVoid) geometryJsx = '<sphereGeometry args={[1.2, 32, 32]} />';
  else if (isGold) geometryJsx = '<boxGeometry args={[1.2, 1.2, 1.2]} />';
  else if (isNature) geometryJsx = '<icosahedronGeometry args={[1.4, 1]} />';
  else if (isFire) geometryJsx = '<dodecahedronGeometry args={[1.3, 0]} />';

  // Select material properties
  let color = '#8b5cf6'; // default purple
  let emissive = '#4c1d95';
  let roughness = 0.2;
  let metalness = 0.8;
  let distort = 0.3;

  if (isFire) {
    color = '#ff4500';
    emissive = '#ff0000';
    roughness = 0.4;
    metalness = 0.3;
    distort = 0.6;
  } else if (isIce) {
    color = '#e0ffff';
    emissive = '#00ced1';
    roughness = 0.1;
    metalness = 0.9;
    distort = 0.2;
  } else if (isVoid) {
    color = '#111111';
    emissive = '#000000';
    roughness = 0.9;
    metalness = 0.2;
    distort = 0.1;
  } else if (isGold) {
    color = '#ffd700';
    emissive = '#daa520';
    roughness = 0.1;
    metalness = 1.0;
    distort = 0.2;
  } else if (isNature) {
    color = '#4ade80';
    emissive = '#22c55e';
    roughness = 0.6;
    metalness = 0.1;
    distort = 0.5;
  }

  // Animation logic (simple rotation + pulse)
  const animationSpeed = isFire ? 2.5 : (isIce ? 0.2 : 1.0);

  // Random position offset to avoid stacking perfectly in center
  const posX = (Math.random() - 0.5) * 4;
  const posY = (Math.random() - 0.5) * 4;
  const posZ = (Math.random() - 0.5) * 2;

  return `// Auto-generated by Project Genie Simulator
// Directive: ${directive}
// Generated: ${timestamp}

import React, { useRef } from 'react'
import { useFrame } from '@react-three/fiber'
import { MeshDistortMaterial } from '@react-three/drei'
import * as THREE from 'three'

export default function ${name}({ balance = 0, coherence = 100 }) {
  const meshRef = useRef()

  useFrame((state) => {
    if (meshRef.current) {
      const t = state.clock.elapsedTime

      // Dynamic rotation based on coherence
      const rotationSpeed = ${animationSpeed} * (coherence / 100)
      meshRef.current.rotation.x = t * 0.2 * rotationSpeed
      meshRef.current.rotation.y = t * 0.3 * rotationSpeed

      // Pulse effect based on balance
      const scaleBase = 1 + (balance * 0.05)
      const pulse = Math.sin(t * ${animationSpeed}) * 0.1
      meshRef.current.scale.setScalar(scaleBase + pulse)
    }
  })

  return (
    <mesh ref={meshRef} position={[${posX.toFixed(2)}, ${posY.toFixed(2)}, ${posZ.toFixed(2)}]}>
      ${geometryJsx}
      <MeshDistortMaterial
        color="${color}"
        emissive="${emissive}"
        emissiveIntensity={0.5 + balance * 0.2}
        roughness={${roughness}}
        metalness={${metalness}}
        distort={${distort}}
        speed={${animationSpeed}}
      />
    </mesh>
  )
}
`;
};

module.exports = { generateEvolutionComponent };
