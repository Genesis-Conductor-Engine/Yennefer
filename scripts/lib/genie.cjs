// scripts/lib/genie.cjs
// "Project Genie" Simulation Module
// Procedurally generates React Three Fiber components for Yennefer's evolution.
// Mimics the behavior of generative AI for 3D worlds.

const GEOMETRIES = [
  'boxGeometry',
  'sphereGeometry',
  'torusKnotGeometry',
  'icosahedronGeometry',
  'octahedronGeometry',
  'dodecahedronGeometry',
  'coneGeometry',
  'cylinderGeometry'
];

const DREI_MATERIALS = [
  'MeshDistortMaterial',
  'MeshWobbleMaterial'
];

const STANDARD_MATERIALS = [
  'meshStandardMaterial',
  'meshPhysicalMaterial',
  'meshNormalMaterial'
];

const COLORS = [
  '#ef4444', // red-500
  '#f97316', // orange-500
  '#eab308', // yellow-500
  '#84cc16', // lime-500
  '#22c55e', // green-500
  '#10b981', // emerald-500
  '#06b6d4', // cyan-500
  '#3b82f6', // blue-500
  '#6366f1', // indigo-500
  '#8b5cf6', // violet-500
  '#d946ef', // fuchsia-500
  '#f43f5e', // rose-500
  '#ffffff', // white
  '#000000', // black
];

function getRandomItem(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getRandomColor() {
  return getRandomItem(COLORS);
}

function generateEvolutionComponent(name, directive) {
  const geometry = getRandomItem(GEOMETRIES);

  // Decide if using Drei material or Standard material
  const useDrei = Math.random() > 0.5;
  const materialType = useDrei ? getRandomItem(DREI_MATERIALS) : getRandomItem(STANDARD_MATERIALS);

  const color = getRandomColor();
  const emissive = getRandomColor();

  // Geometry args based on type
  let args = '';
  if (geometry === 'boxGeometry') args = 'args={[1, 1, 1]}';
  else if (geometry === 'sphereGeometry') args = 'args={[1, 32, 32]}';
  else if (geometry === 'torusKnotGeometry') args = 'args={[1, 0.3, 100, 16]}';
  else if (geometry === 'icosahedronGeometry') args = 'args={[1, 0]}';
  else if (geometry === 'octahedronGeometry') args = 'args={[1, 0]}';
  else if (geometry === 'dodecahedronGeometry') args = 'args={[1, 0]}';
  else if (geometry === 'coneGeometry') args = 'args={[1, 2, 32]}';
  else if (geometry === 'cylinderGeometry') args = 'args={[1, 1, 2, 32]}';

  // Material props
  let materialProps = `color="${color}"`;

  if (materialType !== 'meshNormalMaterial') {
     // Normal material doesn't take color/emissive usually the same way, but it's fine to pass extra props in R3F
     if (materialType.startsWith('Mesh') || materialType === 'meshStandardMaterial' || materialType === 'meshPhysicalMaterial') {
         materialProps += ` emissive="${emissive}" emissiveIntensity={0.5 + balance}`;
         materialProps += ` roughness={0.2} metalness={0.8}`;
     }
  }

  if (materialType === 'MeshDistortMaterial') {
    materialProps += ` distort={0.4} speed={2}`;
  }
  if (materialType === 'MeshWobbleMaterial') {
    materialProps += ` factor={0.6} speed={2}`;
  }

  // Imports
  const imports = [
    "import React, { useRef } from 'react'",
    "import { useFrame } from '@react-three/fiber'",
    "import { MeshDistortMaterial, MeshWobbleMaterial } from '@react-three/drei'"
  ].join('\n');

  // Animation logic
  const animationType = Math.floor(Math.random() * 3);
  let animationCode = '';

  if (animationType === 0) {
    // Rotation + Bobbing
    animationCode = `
      meshRef.current.rotation.x = state.clock.elapsedTime * 0.5;
      meshRef.current.rotation.y = state.clock.elapsedTime * 0.3;
      meshRef.current.position.y = Math.sin(state.clock.elapsedTime) * 0.2;
    `;
  } else if (animationType === 1) {
    // Scaling + Spinning
    animationCode = `
      meshRef.current.rotation.z += 0.01;
      const scale = 1 + Math.sin(state.clock.elapsedTime * 2) * 0.3;
      meshRef.current.scale.setScalar(scale + balance * 0.5);
    `;
  } else {
    // Chaos
    animationCode = `
      meshRef.current.rotation.x += 0.02;
      meshRef.current.rotation.y += 0.03;
      meshRef.current.rotation.z += 0.01;
    `;
  }

  return `// Auto-generated by Project Genie Integration
// Directive: ${directive}
// Generated: ${new Date().toISOString()}

${imports}

export default function ${name}({ balance = 0 }) {
  const meshRef = useRef()

  useFrame((state) => {
    if (meshRef.current) {
      ${animationCode}
    }
  })

  return (
    <mesh ref={meshRef}>
      <${geometry} ${args} />
      <${materialType}
        ${materialProps}
      />
    </mesh>
  )
}
`;
}

module.exports = { generateEvolutionComponent };
