/**
 * Generates a React Three Fiber component string based on a directive.
 *
 * @param {string} name - The name of the component (e.g., 'Mutation123')
 * @param {string} directive - The directive or prompt for generation
 * @returns {string} The JSX component code
 */
function generateEvolutionComponent(name, directive) {
  // Sanitize directive to prevent injection via newlines
  const safeDirective = directive.replace(/[\n\r]/g, ' ').replace(/["`]/g, "'");

  // --- PROJECT GENIE INTEGRATION PLACEHOLDER ---
  // In a future version, this function could call the Project Genie API:
  // const genieWorld = await callProjectGenieAPI(safeDirective);
  // return convertGenieToR3F(genieWorld);
  // ---------------------------------------------

  // PROCEDURAL GENERATION LOGIC
  const geometries = [
    '<boxGeometry args={[1, 1, 1]} />',
    '<sphereGeometry args={[0.7, 32, 32]} />',
    '<torusGeometry args={[0.6, 0.2, 16, 100]} />',
    '<octahedronGeometry args={[1, 0]} />',
    '<icosahedronGeometry args={[1, 0]} />',
    '<dodecahedronGeometry args={[1, 0]} />',
    '<torusKnotGeometry args={[0.6, 0.2, 100, 16]} />'
  ];

  const materials = [
    (color) => `<meshStandardMaterial color="${color}" roughness={0.3} metalness={0.8} />`,
    (color) => `<MeshDistortMaterial color="${color}" speed={2} distort={0.4} roughness={0.2} />`,
    (color) => `<MeshWobbleMaterial color="${color}" factor={1} speed={2} />`,
    (color) => `<meshNormalMaterial />`,
    (color) => `<meshPhysicalMaterial color="${color}" transmission={0.6} thickness={1} roughness={0.2} />`
  ];

  // Random selection
  const geometry = geometries[Math.floor(Math.random() * geometries.length)];
  const materialFunc = materials[Math.floor(Math.random() * materials.length)];

  // Generate a random color based on directive hash or random
  const colors = ['#8b5cf6', '#ef4444', '#10b981', '#3b82f6', '#f59e0b', '#ec4899', '#6366f1'];
  const color = colors[Math.floor(Math.random() * colors.length)];
  const material = materialFunc(color);

  const rotSpeedX = (Math.random() * 0.02 - 0.01).toFixed(4);
  const rotSpeedY = (Math.random() * 0.02 - 0.01).toFixed(4);

  return `// Auto-generated by Yennefer Genie Engine
// Directive: ${safeDirective}
// Generated: ${new Date().toISOString()}

import React, { useRef } from 'react'
import { useFrame } from '@react-three/fiber'
import { MeshDistortMaterial, MeshWobbleMaterial } from '@react-three/drei'

export default function ${name}({ balance = 0, coherence = 100 }) {
  const meshRef = useRef()

  useFrame((state) => {
    if (meshRef.current) {
      meshRef.current.rotation.x += ${rotSpeedX}
      meshRef.current.rotation.y += ${rotSpeedY}

      // Responsive behavior
      const pulse = Math.sin(state.clock.elapsedTime * 2) * 0.1
      const scaleBase = 1 + (balance * 0.1)
      meshRef.current.scale.setScalar(scaleBase + pulse)
    }
  })

  return (
    <mesh ref={meshRef} position={[${(Math.random() * 4 - 2).toFixed(2)}, ${(Math.random() * 4 - 2).toFixed(2)}, ${(Math.random() * 2 - 1).toFixed(2)}]}>
      ${geometry}
      ${material}
    </mesh>
  )
}
`;
}

module.exports = { generateEvolutionComponent };
